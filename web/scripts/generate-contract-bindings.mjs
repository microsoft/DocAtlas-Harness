import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const workspaceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const contractRoot = resolve(workspaceRoot, 'contracts')
const checkOnly = process.argv.includes('--check')

const outputPaths = {
  browser: resolve(workspaceRoot, 'packages/contracts/src/generated-browser-validators.ts'),
  typescript: resolve(workspaceRoot, 'packages/contracts/src/generated-schema-registry.ts'),
  python: resolve(
    workspaceRoot,
    'python/docatlas-sidecar/src/docatlas_dsh_sidecar/generated_schema_bundle.py',
  ),
}

async function readJson(path) {
  return JSON.parse(await readFile(path, 'utf8'))
}

const catalog = await readJson(resolve(contractRoot, 'schema-catalog.json'))
if (catalog?.schemaVersion !== 1 || !Array.isArray(catalog.schemas)) {
  throw new Error('contracts/schema-catalog.json must be a schemaVersion 1 catalog')
}

const seenNames = new Set()
const seenIds = new Set()
const schemas = {}
for (const entry of catalog.schemas) {
  if (typeof entry?.name !== 'string' || typeof entry.path !== 'string' || typeof entry.id !== 'string') {
    throw new Error('every schema catalog entry requires string name/path/id')
  }
  if (seenNames.has(entry.name)) throw new Error(`duplicate schema name: ${entry.name}`)
  if (seenIds.has(entry.id)) throw new Error(`duplicate schema id: ${entry.id}`)
  seenNames.add(entry.name)
  seenIds.add(entry.id)

  const schema = await readJson(resolve(contractRoot, entry.path))
  if (schema?.$id !== entry.id) {
    throw new Error(`catalog id mismatch for ${entry.name}: ${String(schema?.$id)}`)
  }
  schemas[entry.name] = schema
}

const prettyCatalog = JSON.stringify(catalog, null, 2)
const prettySchemas = JSON.stringify(schemas, null, 2)
const compactBundle = JSON.stringify({ catalog, schemas })
if (compactBundle.includes("'''")) throw new Error('schema bundle cannot contain Python delimiter')

const requireContracts = createRequire(resolve(workspaceRoot, 'packages/contracts/package.json'))
const { Ajv2020 } = requireContracts('ajv/dist/2020.js')
const addFormats = requireContracts('ajv-formats')
const standalone = requireContracts('ajv/dist/standalone/index.js').default
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } })
addFormats(ajv)
for (const schema of Object.values(schemas)) ajv.addSchema(schema)
const names = { productLearning: 'product-learning', humanResearch: 'human-research', nativeLineage: 'native-lineage', nativeControl: 'native-control', productHistory: 'product-history', productHttp: 'product-http', productControl: 'product-control', observations: 'conversation-observation', documentHttp: 'document-http', enrichment: 'enrichment', productAnswer: 'product-answer', productResearch: 'product-research', productPersonalization: 'product-personalization', productPersonalizationV2: 'product-personalization-v2', productReview: 'product-review', productLibrary: 'product-library', productContinuity: 'product-continuity', productProbe: 'product-probe' }
names.questionContext = 'question-context'
let browserCode = standalone(ajv, Object.fromEntries(Object.entries(names).map(([name, key]) => [name, schemas[key].$id])))
const imports = []
browserCode = browserCode.replace(/require\("(ajv(?:-formats)?\/[^"\n]+)"\)(?:\.([A-Za-z0-9_]+))?/g, (_match, path, property) => {
  const name = `runtimeDependency${imports.length}`
  if (!['ajv/dist/runtime/ucs2length', 'ajv/dist/runtime/equal', 'ajv-formats/dist/formats'].includes(path)) throw new Error(`Unreviewed browser validator runtime: ${path}`)
  imports.push(property && property !== 'default' ? `import { ${property} as ${name} } from '${path}.js'`
    : `import ${name}Module from '${path}.js'\nconst ${name} = typeof ${name}Module === 'function' ? ${name}Module : ${name}Module.default`)
  return name
})
if (/\brequire\(|new Function\(/.test(browserCode)) throw new Error('Browser contracts must be static ESM without runtime eval')

const outputs = {
  browser: `// @ts-nocheck\n/* Generated static browser validators; do not edit. */\n/* oxlint-disable */\n${imports.join('\n')}\n${browserCode}\n`,
  typescript: `/* This file is generated by scripts/generate-contract-bindings.mjs. Do not edit. */
/* oxlint-disable unicorn/no-thenable -- JSON Schema conditionals use the standard "then" keyword. */

export const SCHEMA_CATALOG = ${prettyCatalog} as const

export const SCHEMA_DEFINITIONS = ${prettySchemas} as const
`,
  python: `"""Generated canonical schema bundle. Do not edit by hand."""

from __future__ import annotations

import json
from typing import Any, Final

_BUNDLE_JSON: Final = r'''${compactBundle}'''
SCHEMA_BUNDLE: Final[dict[str, Any]] = json.loads(_BUNDLE_JSON)

__all__ = ["SCHEMA_BUNDLE"]
`,
}

async function updateOrCheck(label, path, expected) {
  let actual = null
  try {
    actual = await readFile(path, 'utf8')
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error
  }

  if (actual === expected) return false
  if (checkOnly) {
    throw new Error(`${label} generated contract bundle is stale; run pnpm generate:contracts`)
  }
  await writeFile(path, expected, 'utf8')
  return true
}

const changed = []
for (const [label, path] of Object.entries(outputPaths)) {
  if (await updateOrCheck(label, path, outputs[label])) changed.push(label)
}

console.log(
  checkOnly
    ? `generated contract bundles verified (${Object.keys(outputPaths).join(', ')})`
    : changed.length > 0
      ? `generated contract bundles updated (${changed.join(', ')})`
      : 'generated contract bundles already current',
)
